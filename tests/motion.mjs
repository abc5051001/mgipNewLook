import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.BASE_URL || 'http://127.0.0.1:5174';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'no-preference' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(base, { waitUntil: 'networkidle' });
  const numbers = page.locator('.mg-stat strong>span[aria-hidden=true]');
  assert.deepEqual(await numbers.allTextContents(), ['0', '0+', '0+', '0']);
  await page.locator('.mg-original-stats').scrollIntoViewIfNeeded();
  await expect.poll(async () => Number(await numbers.first().textContent())).toBeGreaterThan(0);
  assert.ok(Number(await numbers.first().textContent()) < 2006, 'The counter should show intermediate values.');
  await expect(numbers.first()).toHaveText('2006');
  assert.deepEqual(await numbers.allTextContents(), ['2006', '60+', '9+', '8']);
  await page.evaluate(() => window.scrollTo({top:0,behavior:'instant'}));
  await expect(numbers.first()).toHaveText('0');
  await page.locator('.mg-original-stats').scrollIntoViewIfNeeded();
  await expect.poll(async () => Number(await numbers.first().textContent())).toBeGreaterThan(0);
  assert.ok(Number(await numbers.first().textContent()) < 2006,'Counter should replay after returning to the section.');
  await expect(numbers.first()).toHaveText('2006');
  await page.getByRole('tab', { name: /Trademark/ }).click();
  const trademark = page.locator('.mg-trademark-machine');
  await trademark.scrollIntoViewIfNeeded();
  await expect(trademark).toHaveAttribute('data-active', 'true');
  const stamp=trademark.getByRole('slider');
  const initialStamp=await stamp.getAttribute('data-progress');
  await expect.poll(()=>stamp.getAttribute('data-progress')).not.toBe(initialStamp);
  await page.screenshot({ path: 'test-results/trademark-desktop.png' });
  await page.getByRole('tab', { name: /Copyright/ }).click();
  const rights = page.locator('.mg-copyright-machine');
  await rights.scrollIntoViewIfNeeded();
  await expect(rights).toHaveAttribute('data-active', 'true');
  const carriage=rights.locator('[data-group="carriage"]').first();
  const before=await carriage.getAttribute('transform');
  await expect.poll(()=>carriage.getAttribute('transform')).not.toBe(before);
  await page.screenshot({ path: 'test-results/copyright-desktop.png' });
  await page.locator('.mg-benefits-section').scrollIntoViewIfNeeded();
  await expect(rights).toHaveAttribute('data-active', 'false');
  const stopped=await carriage.getAttribute('transform');
  await page.waitForTimeout(200);
  assert.equal(await carriage.getAttribute('transform'),stopped);
  await page.locator('.mg-benefit-card').last().scrollIntoViewIfNeeded();
  await expect(page.locator('.mg-benefit-card').last()).toHaveCSS('opacity', '1');
  await page.locator('.mg-benefits-section').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/benefits-desktop.png' });
  const cards = await page.locator('.mg-benefit-card').evaluateAll(elements => elements.map(el => ({ color: getComputedStyle(el).backgroundColor, width: el.getBoundingClientRect().width })));
  assert.equal(new Set(cards.map(card => card.color)).size, 6);
  await expect(page.locator('.mg-collective-mosaic>a')).toHaveCount(43);
  const sizes = await page.locator('.mg-collective-mosaic>a').evaluateAll(elements => elements.map(el => Math.round(el.getBoundingClientRect().width)));
  assert.equal(new Set(sizes).size, 1, 'Every homepage profile has equal visual weight.');
  await page.goto(base + '/team');
  await expect(page.locator('.mg-team-hero img')).toHaveCount(0);
  await expect(page.locator('.mg-team-grid .mg-person')).toHaveCount(43);
  await expect(page.locator('.mg-art-portrait')).toHaveCount(0);
  await expect(page.locator('.mg-team-hero-copy')).toHaveCSS('opacity', '1');
  await expect(page.locator('.mg-team-linework')).toHaveCount(1);
  await expect(page.locator('.mg-team-panorama')).toHaveCount(0);
  await expect(page.getByRole('link',{name:'Explore the team',exact:true})).toHaveCount(0);
  const collaboration=page.locator('.mg-team-collaboration');
  const network=collaboration.locator('.mg-figure svg');
  const networkFrame=()=>network.evaluate(el=>[...el.querySelectorAll('.mg-team-module,.mg-team-signal')].map(part=>{
    const style=getComputedStyle(part);return style.transform+'|'+style.strokeDashoffset;
  }).join(';'));
  await expect(collaboration).toHaveAttribute('data-active','true');
  await expect(network).toBeVisible();
  await expect(collaboration.locator('.mg-team-person-card,.mg-team-person-mark')).toHaveCount(0);
  const networkStart=await networkFrame();
  await expect.poll(networkFrame).not.toBe(networkStart);
  await network.hover();
  const hoveredNetwork=await networkFrame();
  await expect.poll(networkFrame).not.toBe(hoveredNetwork);
  await page.getByRole('button',{name:'Pause team illustration',exact:true}).click();
  await expect(collaboration).toHaveAttribute('data-active','false');
  await network.evaluate(el=>Promise.all(el.getAnimations({subtree:true}).map(animation=>animation.ready)));
  const pausedNetwork=await networkFrame();
  await page.waitForTimeout(200);assert.equal(await networkFrame(),pausedNetwork);
  await page.getByRole('button',{name:'Play team illustration',exact:true}).click();
  await expect(collaboration).toHaveAttribute('data-active','true');
  await page.screenshot({ path: 'test-results/team-hero-desktop.png' });
  await page.locator('.mg-footer').scrollIntoViewIfNeeded();
  await expect(collaboration).toHaveAttribute('data-active','false');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await expect(collaboration).toHaveAttribute('data-active','true');
  await page.goto(base + '/careers');
  await expect(page.locator('.mg-careers-terrain')).toHaveAttribute('data-active', 'true');
  await expect(page.locator('.mg-drafting-figure')).toHaveCount(0);
  await expect(page.locator('.mg-page-copy')).toHaveCSS('opacity', '1');
  await page.screenshot({ path: 'test-results/careers-hero-desktop.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(base+'/team');
  await expect(collaboration).toHaveAttribute('data-active','false');
  await expect(network).toBeVisible();
  const reducedNetwork=await networkFrame();
  await page.waitForTimeout(200);assert.equal(await networkFrame(),reducedNetwork);
  await expect(page.getByRole('button',{name:'Pause team illustration',exact:true})).toHaveCount(0);
  await page.goto(base);
  assert.deepEqual(await numbers.allTextContents(), ['2006', '60+', '9+', '8']);
  await page.getByRole('tab', { name: /Copyright/ }).click();
  await rights.scrollIntoViewIfNeeded();
  await expect(rights).toHaveAttribute('data-active', 'false');
  await expect(rights.getByRole('slider')).toHaveAttribute('data-progress','1.0000');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.mg-benefits-section').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/benefits-mobile.png' });
  assert.deepEqual(errors, []);
  console.log('Count-up replay, live artwork, offscreen pause, reduced motion, colored cards, and full-width equal team presentation passed.');
} finally { await browser.close(); }
