import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
const base=process.env.BASE_URL||'http://127.0.0.1:5174';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'no-preference'});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/team',{waitUntil:'networkidle'});
  await expect(page.locator('.mg-team-hero img')).toHaveCount(0);
  await expect(page.locator('.mg-team-grid .mg-person')).toHaveCount(43);
  await expect(page.locator('.mg-team-linework')).toBeVisible();
  await page.goto(base+'/careers');
  const career=page.locator('.mg-careers-terrain');
  await expect(career.locator('.mg-figure svg')).toBeVisible();
  await expect(page.locator('.mg-drafting-figure')).toHaveCount(0);
  await expect(career).toHaveAttribute('data-active','true');
  await page.getByRole('button',{name:'Pause career illustration'}).click();
  await expect(career).toHaveAttribute('data-active','false');
  await page.getByRole('button',{name:'Play career illustration'}).click();
  await expect(career).toHaveAttribute('data-active','true');
  await page.getByRole('link',{name:'MG-IP home',exact:true}).click();
  await expect(page).toHaveURL(base+'/');
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(0);
  await page.getByRole('link',{name:'Learn More',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBeGreaterThan(0);
  await page.getByRole('link',{name:'MG-IP home',exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(0);
  await page.locator('.mg-footer-logo').click();
  await expect.poll(()=>page.evaluate(()=>scrollY)).toBe(0);
  await expect(page.locator('.mg-header')).toHaveAttribute('data-scrolled','false');
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'About',exact:true})).toHaveAttribute('aria-current','page');
  await page.goto(base+'/disclaimer');
  const responsibility=page.locator('.mg-legal>section').last();
  await expect(responsibility).toContainText('Scott Tulino is responsible for ensuring the accuracy of all content on this website.');
  await responsibility.getByRole('link',{name:'Scott Tulino',exact:true}).click();
  await expect(page).toHaveURL(base+'/team/Scott.T');
  await expect(page.getByRole('heading',{level:1})).toHaveText('Scott M. Tulino');
  await page.goto(base+'/');
  await page.getByRole('tab',{name:/Trademark/}).click();
  const stamp=page.locator('.mg-trademark-machine'),stage=stamp.getByRole('slider');
  await stamp.scrollIntoViewIfNeeded();
  await expect.poll(async()=>Number(await stage.getAttribute('data-progress')),{timeout:6000}).toBeGreaterThan(.75);
  await expect(stamp.locator('text')).toContainText('\u2122');
  await stage.hover({position:{x:200,y:100}});
  await page.waitForTimeout(1500);
  const restingPointer=await stage.getAttribute('data-progress');
  await expect.poll(()=>stage.getAttribute('data-progress')).not.toBe(restingPointer);
  const footer=page.locator('.mg-footer-geometry'),drawing=footer.locator('.mg-figure svg');
  const drawingFrame=()=>drawing.evaluate(el=>[...el.querySelectorAll('.mg-patent-layer')].map(part=>getComputedStyle(part).transform).join(';'));
  await footer.scrollIntoViewIfNeeded();
  await expect(footer).toHaveAttribute('data-active','true');
  await expect(drawing).toBeVisible();
  const before=await drawingFrame();
  await expect.poll(drawingFrame).not.toBe(before);
  await drawing.hover();
  const hovered=await drawingFrame();
  await expect.poll(drawingFrame).not.toBe(hovered);
  await page.getByRole('button',{name:'Pause footer animation'}).click();
  await expect(footer).toHaveAttribute('data-active','false');
  await drawing.evaluate(el=>Promise.all(el.getAnimations({subtree:true}).map(animation=>animation.ready)));
  const paused=await drawingFrame();
  await page.waitForTimeout(200);assert.equal(await drawingFrame(),paused);
  await page.getByRole('button',{name:'Play footer animation'}).click();
  await expect(footer).toHaveAttribute('data-active','true');
  await page.emulateMedia({reducedMotion:'reduce'});
  const reducedDrawing=await drawingFrame();
  await page.waitForTimeout(200);assert.equal(await drawingFrame(),reducedDrawing);
  await expect(page.getByRole('button',{name:'Pause footer animation'})).toBeHidden();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await expect(footer).toHaveAttribute('data-active','false');
  await expect(drawing).toHaveCount(0);
  await footer.scrollIntoViewIfNeeded();
  await expect(footer).toHaveAttribute('data-active','true');
  await expect(drawing).toBeVisible();
  await page.emulateMedia({reducedMotion:'reduce'});
  for(const width of [320,390,600,720,768,1440]){
    await page.setViewportSize({width,height:844});
    for(const path of ['/','/team','/careers','/disclaimer']){
      await page.goto(base+path);
      assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${width}px overflow on ${path}`);
    }
  }
  await page.setViewportSize({width:390,height:844});await page.goto(base+'/');
  await expect(page.locator('.mg-home-photo-background')).toHaveCSS('position','absolute');
  await expect(page.locator('.mg-home-scroll')).toBeVisible();
  await expect(page.locator('.mg-hero-disciplines')).toHaveCount(0);
  await expect(page.getByRole('heading',{level:1})).toBeInViewport();
  await expect(page.getByRole('link',{name:'Learn More',exact:true})).toBeInViewport();
  await page.screenshot({path:'test-results/revision-home-mobile-final.png'});
  assert.deepEqual(errors,[]);
  console.log('Team portraits appear once; Careers terrain, both home-logo paths, Scott attribution/link, faster idle motion, footer autoplay/pause, reduced motion and responsive mobile hero passed.');
}finally{await browser.close();}
